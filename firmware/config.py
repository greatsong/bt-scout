# 감지기마다 이 파일의 GRADE, CLASSES, AP_CHANNEL만 바꿔서 넣는다.

# 이 감지기가 맡은 교실. 대시보드가 이 값으로 자리를 잡는다.
#
#   감지기 8대          GRADE   CLASSES   AP_CHANNEL
#   1학년 1,2반           1      "1,2"        1
#   1학년 3,4반           1      "3,4"        6
#   1학년 5,6반           1      "5,6"       11
#   1학년 7,8반           1      "7,8"        1
#   2학년 1,2반           2      "1,2"        6
#   2학년 3,4반           2      "3,4"       11
#   2학년 5,6반           2      "5,6"        1
#   2학년 7,8반           2      "7,8"        6
GRADE = 1                # 학년: 1 또는 2
CLASSES = "1,2"          # 맡은 두 반: "1,2" "3,4" "5,6" "7,8" (띄어쓰기 없이)
UNIT = "%d학년 %s반" % (GRADE, CLASSES)   # 화면에 나오는 이름. 예: 1학년 1,2반 (고치지 않는다)

# 확인용 와이파이(피코가 직접 만드는 것. 학교 와이파이와 무관)
# 8대 모두 같은 이름·암호로 두면, 복도를 걸을 때 휴대전화가 가까운 감지기로 저절로 옮겨 붙는다.
AP_SSID = "SCOUT"
AP_PASSWORD = "12345678"         # 기본 암호. 학교에서 쓸 때는 꼭 다른 값(8자 이상)으로 바꾼다. 8대 모두 같게.
AP_CHANNEL = 1                   # 이웃 감지기끼리 1, 6, 11을 번갈아 쓴다.

# 그로브 쉴드 포트
# ---- LED ----
# "stick"  = 색이 바뀌는 LED 줄(네오픽셀: WS2812, WS2813). Grove RGB LED Stick 10개, LED 띠 60개 등
# "single" = 색이 하나인 LED 한 개(Grove LED 등)
# 피코 본체의 작은 초록 LED는 종류와 상관없이 항상 함께 동작한다.
LED_TYPE = "stick"
LED_PIN = 16             # LED → D16 포트
LED_COUNT = 10           # LED 개수. 10개짜리면 10, 60개짜리면 60. 이 숫자만 바꾸면 된다.
LED_BRIGHT = 40          # 밝기 1~255. 복도에서 잘 안 보이면 80까지 올린다.

# 아래는 보통 그대로 둔다.
LED_KHZ = 800            # 신호 속도. 요즘 LED(WS2812·WS2813)는 800. 아주 오래된 것만 400.
LED_ORDER = "GRB"        # 색 순서. 빨강이 초록으로 나오면 "RGB"로 바꾼다.
LED_MAX_MA = 250         # LED 전체가 쓸 전류 한도(mA). 넘으면 밝기를 저절로 낮춘다.
                         # USB 전원을 지키기 위한 값이다. 따로 5V 전원을 달았을 때만 올린다.

# 판정 기준(화면에서 바꾼 값은 settings.json에 따로 저장되어 이 값보다 우선한다)
RSSI_MIN = -75           # 이 세기 이상을 '교실 안'으로 본다. 현장 측정 후 조정.
PERSIST = 10             # 이 시간(초) 이상 계속 잡혀야 감지. 복도 통행인을 거른다.
HOLD = 60                # 마지막으로 잡힌 뒤 LED를 켜 두는 시간(초)

# 블루투스 듣기 비중. 블루투스와 와이파이가 안테나 하나를 나눠 쓴다.
# 휴대전화가 SCOUT에 잘 안 붙으면 WINDOW를 20으로 줄이고, 감지가 느리면 80으로 늘린다.
BLE_INTERVAL_MS = 200    # 이 간격(ms)마다
BLE_WINDOW_MS = 40       # 이만큼(ms) 듣는다
BLE_ACTIVE = False       # True면 기기 이름을 더 잘 알아내지만 전파를 더 쓴다

# ESP32 와이파이 청취기 (그로브 UART1 포트). 달지 않은 감지기는 False.
SNIFFER = False          # ESP32를 단 감지기만 True로 바꾼다.
STA_RSSI_MIN = -70       # 와이파이를 켠 기기를 '교실 안'으로 보는 세기

# 광대역 전파 세기 센서 AD8317 (그로브 A0 포트). 단 감지기만 True.
RF_SENSOR = False
RF_ALERT = False         # True면 급증 때 LED도 켠다. 오탐 정도를 재 본 뒤에 켠다.
RF_DELTA = 10            # 평소보다 이만큼(dB) 세면 급증으로 센다.
RF_SLOPE = 0.022         # 센서 출력: 1dB당 전압 변화(V). AD8317 기준 약 0.022
RF_INTERCEPT = 15        # 출력 전압이 0V가 되는 세기(dBm). AD8317 기준 약 15

# 핫스팟 탐지(피코가 주변 와이파이를 직접 훑는다). ESP32 청취기(SNIFFER)가 없을 때 쓰인다.
WIFI_SCAN = True         # 핫스팟을 잡는다. 화면 접속이 자주 끊기면 False로 바꾼다.
WIFI_RSSI_MIN = -70      # 이 세기 이상인 새 와이파이 신호를 감지로 본다.
WIFI_EVERY = 20          # 평소 훑는 간격(초). 두 번 연속 잡혀야 감지하므로 약 40초 걸린다.
WIFI_EVERY_VIEWING = 60  # 누군가 화면을 보고 있을 때의 간격(초). 훑는 2~3초 동안 화면이 멈춘다.

# 정밀 탐색: 화면에서 기기 하나를 골라 그 신호 세기만 빠르게 따라간다(감지기를 들고 다니며 찾을 때).
HUNT_SECS = 300          # 시작한 뒤 이 시간(초)이 지나면 평소 감지로 돌아간다.
HUNT_INTERVAL_MS = 60    # 탐색 중 블루투스를 듣는 주기. 평소보다 훨씬 자주 듣는다.
HUNT_WINDOW_MS = 45      # 주기마다 듣는 시간. 화면이 자주 끊기면 30으로 줄인다.

HISTORY_HOURS = 6        # 대시보드에 보여 줄 기록 시간. 전원이 꺼지면 기록은 사라진다.

WATCHDOG = False         # True면 멈췄을 때 스스로 다시 시작한다. 현장 시험 뒤 켠다.
